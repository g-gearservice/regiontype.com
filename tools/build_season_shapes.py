def profile(add, cut):
    inside = lambda x, y: any(f(x, y) for f in add) and not any(f(x, y) for f in cut)
    rs = []
    for i in range(N):
        a = i / N * 2 * math.pi
        c, s = math.cos(a), math.sin(a)
        t = 2.0
        while t > 0 and not inside(t * c, t * s):
            t -= 0.004
        rs.append(t)
    peak = max(rs)
    rs = [max(0.4, min(1.3, r / peak * 1.25)) for r in rs]
    # 이웃과 한 번 고른다 — 뾰족한 데가 톱니로 튀지 않게(아주 살짝)
    rs = [0.2 * rs[i - 1] + 0.6 * rs[i] + 0.2 * rs[(i + 1) % N] for i in range(N)]
    return [round(r, 3) for r in rs]


